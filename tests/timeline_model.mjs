import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseNSRT,rebind,move,calibrate,exportTimeline,History,regions} from '../web/timeline.mjs';
const raw='EncounterID:3492;Difficulty:Mythic;Name:Ulatek;\n'+[1,1.5,1.75,2.5].map((ph,i)=>`ph:${ph};time:${i?10:135.5};tag:252;spellid:42650;`).join('\n');
const personalText=readFileSync(new URL('./fixtures/ulatek-heroic-personal.nsrt',import.meta.url),'utf8');
const personal=parseNSRT(personalText);
assert.equal(personal.rows.length,18);assert.equal(personal.difficulty,'heroic');
assert.equal(personal.rows[0].source.tag,undefined);
assert.equal(personal.rows[0].source.raw,'ph:1;time:3.9;spellid:42650;');
assert.ok(!exportTimeline(personal).includes('sourcetag:undefined'));
let draft=parseNSRT(raw);
assert.equal(draft.original,raw);
assert.equal(draft.rows[0].anchor,'mechanic:heart');
assert.equal(draft.rows[0].offset,-10);
assert.equal(draft.rows[0].fallback,135.5);
assert.throws(()=>exportTimeline(draft),/起点/);
draft.starts={'1':0,'1.5':200,'1.75':250,'2.5':300};draft=rebind(draft);
assert.equal(draft.rows[1].absolute,210);
const history=new History(draft);history.set(move(draft,1,140));
assert.equal(history.value.rows[0].absolute,140);history.undo();assert.equal(history.value.rows[0].absolute,135.5);history.redo();assert.equal(history.value.rows[0].absolute,140);
const calibrated=calibrate(draft,{encounterID:3492,difficulty:'mythic',source:'fixture, not LIVE',mechanics:{'heart:1':150}});
const locked=move(draft,1,140);
assert.deepEqual(calibrate(locked,{encounterID:3492,difficulty:'mythic',source:'fixture',mechanics:{'heart:1':160}}).rows[0],locked.rows[0]);
assert.equal(regions(calibrated).find(r=>r.anchor==='mechanic:heart').at,150);
assert.throws(()=>calibrate(draft,{encounterID:1}),/首领/);
const unsafe=structuredClone(draft);unsafe.rows[0].timing='signal';assert.throws(()=>exportTimeline(unsafe),/信号/);
assert.deepEqual(draft.rows.map(r=>r.source.phase),[1,1.5,1.75,2.5]);
process.stdout.write(JSON.stringify({text:exportTimeline(draft),raw}));
